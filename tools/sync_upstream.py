#!/usr/bin/env python
"""Fetch upstream ECC, refresh pool/, and replay the local selection.

    python tools/sync_upstream.py            # fetch + refresh pool + replay selection
    python tools/sync_upstream.py --pool-only # only refresh pool
    python tools/sync_upstream.py --no-fetch  # reuse the existing .upstream clone

Pool layout mirrors the upstream repo paths the assets come from:
    pool/skills/   <- upstream pi/core/skills/
    pool/commands/ <- upstream pi/core/commands/
    pool/agents/   <- upstream agents/

Upstream `pi/core/` is a **committed** artifact of the upstream repository
(generated by scripts/build-pi-core.js, but checked in).  This script only
reads it; it never regenerates it inside a checkout, because the upstream
generator does `rm -rf pi/core` + rename and would therefore mutate the
checkout in place (including the read-only omp marketplace cache clone).
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UPSTREAM_DIR = os.path.join(ROOT, ".upstream")
POOL = os.path.join(ROOT, "pool")
UPSTREAM_MANIFEST = os.path.join(ROOT, "manifest", "upstream.json")
REPO_URL = "https://github.com/affaan-m/ECC"
MARKETPLACE_CACHE = os.path.join(
    os.path.expanduser("~"), ".omp", "plugins", "cache", "marketplaces", "ecc"
)


def run(cmd, cwd=None):
    print("$", " ".join(cmd))
    return subprocess.run(cmd, cwd=cwd, check=True).returncode


def warn(msg):
    print(f"WARNING: {msg}")


# --------------------------------------------------------------------------
# content comparison helpers
# --------------------------------------------------------------------------

def file_sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def tree_digest(root):
    """Map every regular file under `root` to its content hash.

    Relative POSIX-style path -> sha256.  Directories themselves are not
    listed; an empty directory therefore compares equal to a missing one,
    which is acceptable for skill payload comparison.
    """
    digest = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            if not os.path.isfile(full) or os.path.islink(full):
                continue
            digest[os.path.relpath(full, root).replace(os.sep, "/")] = file_sha256(full)
    return digest


def dirs_equal(a, b):
    """Recursive content comparison of two directories.

    `filecmp.dircmp` only compares the *top level* of two directories, so a
    changed file inside `references/` or `scripts/` was invisible.  This
    compares the full relative-path set plus every file's content hash.
    """
    if not os.path.isdir(b):
        return False
    return tree_digest(a) == tree_digest(b)


def files_equal(a, b):
    if not os.path.isfile(b):
        return False
    if os.path.getsize(a) != os.path.getsize(b):
        return False
    return file_sha256(a) == file_sha256(b)


# --------------------------------------------------------------------------
# source resolution / fetching
# --------------------------------------------------------------------------

def resolve_source():
    """Return an ECC checkout to read from, and whether it is ours to update.

    Preference order:
      1. the local .upstream clone managed by this script
      2. the omp marketplace cache clone (same upstream, kept fresh by
         `omp plugin marketplace update ecc`) -- treated as READ ONLY
      3. a fresh clone into .upstream
    """
    if os.path.isdir(os.path.join(UPSTREAM_DIR, ".git")):
        return UPSTREAM_DIR, True
    if os.path.isdir(os.path.join(MARKETPLACE_CACHE, ".git")):
        return MARKETPLACE_CACHE, False
    if os.path.isdir(UPSTREAM_DIR):
        shutil.rmtree(UPSTREAM_DIR)
    run(["git", "-c", "http.version=HTTP/1.1", "clone", "--depth", "1", REPO_URL, UPSTREAM_DIR])
    # The `-c http.version=HTTP/1.1` above only applies to that single call.
    # Persist it in the clone's config so later manual `git fetch` runs do not
    # fall back to HTTP/2 and hit the Windows mid-transfer stream resets.
    run(["git", "-C", UPSTREAM_DIR, "config", "http.version", "HTTP/1.1"])
    return UPSTREAM_DIR, True


def fetch(path, ours):
    if not ours:
        # Read-only source: never fetch, never clean, never reset inside the
        # omp marketplace cache.
        print(f"using omp marketplace cache clone (read-only): {path}")
        check_clean_cache(path)
        return
    # HTTP/2 streams get cancelled mid-transfer on this network; force HTTP/1.1.
    run(["git", "-c", "http.version=HTTP/1.1", "-C", path, "fetch", "--depth", "1", "origin", "HEAD"])
    run(["git", "-C", path, "reset", "--hard", "FETCH_HEAD"])
    run(["git", "-C", path, "clean", "-fdx"])
    # Persist HTTP/1.1 for this clone so future manual fetches behave too.
    run(["git", "-C", path, "config", "http.version", "HTTP/1.1"])


def check_clean_cache(path):
    """Warn when the read-only cache clone carries uncommitted modifications."""
    r = subprocess.run(
        ["git", "-C", path, "status", "--porcelain"],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        warn(f"could not inspect cache clone status: {r.stderr.strip()}")
        return
    lines = [ln for ln in r.stdout.splitlines() if ln.strip()]
    if not lines:
        return
    warn(
        f"omp marketplace cache clone is dirty ({len(lines)} entries); "
        "its working tree is used as the upstream source and may contain "
        "non-upstream files:"
    )
    for ln in lines[:50]:
        print(f"    {ln}")
    if len(lines) > 50:
        print(f"    ... and {len(lines) - 50} more")


def upstream_commit(path):
    return subprocess.run(
        ["git", "-C", path, "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    ).stdout.strip()


def upstream_version(path):
    p = os.path.join(path, "VERSION")
    if os.path.isfile(p):
        return open(p, encoding="utf-8").read().strip()
    return None


def commit_timestamp(path, rev):
    r = subprocess.run(
        ["git", "-C", path, "show", "-s", "--format=%ct", rev],
        capture_output=True, text=True,
    )
    out = r.stdout.strip()
    if r.returncode == 0 and out.isdigit():
        return int(out)
    return None


def is_ancestor(path, older, newer):
    """True when `older` is an ancestor of `newer` inside the repo at `path`."""
    r = subprocess.run(
        ["git", "-C", path, "merge-base", "--is-ancestor", older, newer],
        capture_output=True, text=True,
    )
    return r.returncode == 0


def read_recorded_commit():
    if not os.path.isfile(UPSTREAM_MANIFEST):
        return None
    try:
        with open(UPSTREAM_MANIFEST, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as exc:
        warn(f"cannot read {UPSTREAM_MANIFEST}: {exc}")
        return None
    return data.get("commit")


def report_source(path, ours):
    """Always print which source is used, and compare it with the recorded commit."""
    commit = upstream_commit(path)
    owned = "yes" if ours else "no (omp marketplace cache, read-only)"
    print(f"source: {path}")
    print(f"source owned by this repo: {owned}")
    print(f"source commit: {commit}")

    version = upstream_version(path)
    if version is None:
        warn(f"upstream VERSION file not found in {path} (expected {os.path.join(path, 'VERSION')})")
    else:
        print(f"source version: {version}")

    recorded = read_recorded_commit()
    if recorded is None:
        warn(f"no commit recorded in {UPSTREAM_MANIFEST}; skipping commit comparison")
        return commit, version
    print(f"recorded commit (manifest/upstream.json): {recorded}")
    if recorded == commit:
        print("commit check: identical to recorded commit")
        return commit, version

    # Diverged / moved backwards?
    if is_ancestor(path, commit, recorded):
        warn(
            f"source commit {commit[:12]} is OLDER than the recorded commit "
            f"{recorded[:12]} (the source was rolled back / swapped for an "
            "older checkout) -- refreshing pool from it would downgrade the pool"
        )
    elif is_ancestor(path, recorded, commit):
        print("commit check: source commit is a fast-forward of the recorded commit")
    else:
        new_ts = commit_timestamp(path, commit)
        old_ts = commit_timestamp(path, recorded)
        if new_ts is not None and old_ts is not None and new_ts < old_ts:
            warn(
                f"source commit {commit[:12]} is OLDER than the recorded commit "
                f"{recorded[:12]} (timestamps {new_ts} < {old_ts}) -- the source "
                "looks like an older checkout"
            )
        else:
            warn(
                f"source commit {commit[:12]} differs from the recorded commit "
                f"{recorded[:12]} and the relation could not be determined "
                "(shallow clone history) -- review the pool diff manually"
            )
    return commit, version


# --------------------------------------------------------------------------
# pi/core resolution
# --------------------------------------------------------------------------

def resolve_picore(path):
    """Return the upstream directory that holds the curated pi/core tree.

    `pi/core/` is committed in the upstream repository.  We never regenerate
    it: the upstream generator deletes and renames `pi/core` in place, which
    would mutate the checkout (and the omp marketplace cache is not ours to
    modify).
    """
    committed = os.path.join(path, "pi", "core")
    if os.path.isdir(os.path.join(committed, "skills")):
        return committed, "committed pi/core"
    raise SystemExit(
        f"upstream pi/core not found in {committed}: this upstream commit does "
        "not include pi/core. Use a newer clone (or provide pi/core manually); "
        "this script will not regenerate it in place because the upstream "
        "generator rewrites the checkout it runs in."
    )


# --------------------------------------------------------------------------
# pool refresh
# --------------------------------------------------------------------------

def copy_file(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)


def refresh_pool(path, report, commit, version):
    picore, origin = resolve_picore(path)
    print(f"pi/core source: {origin}")

    mapping = {
        "skills": (os.path.join(picore, "skills"), os.path.join(POOL, "skills"), True),
        "commands": (os.path.join(picore, "commands"), os.path.join(POOL, "commands"), False),
        "agents": (os.path.join(path, "agents"), os.path.join(POOL, "agents"), False),
    }
    for kind, (src, dst, is_dir) in mapping.items():
        if not os.path.isdir(src):
            raise SystemExit(f"upstream {kind} source missing: {src}")
        changed = 0
        added = 0
        removed = 0
        if os.path.isdir(dst):
            for name in sorted(os.listdir(dst)):
                s = os.path.join(src, name)
                d = os.path.join(dst, name)
                if not os.path.exists(s):
                    removed += 1
                    if os.path.isdir(d) and not os.path.islink(d):
                        shutil.rmtree(d)
                    else:
                        os.remove(d)
                    continue
                if is_dir:
                    if not dirs_equal(s, d):
                        changed += 1
                        shutil.rmtree(d)
                        shutil.copytree(s, d)
                else:
                    if not files_equal(s, d):
                        changed += 1
                        copy_file(s, d)
            for name in sorted(os.listdir(src)):
                s = os.path.join(src, name)
                d = os.path.join(dst, name)
                if os.path.exists(d):
                    continue
                added += 1
                if is_dir:
                    shutil.copytree(s, d)
                else:
                    copy_file(s, d)
        else:
            # Target does not exist yet: copy the whole tree in one go.
            # Do NOT pre-create the destination (copytree would then fail with
            # FileExistsError).
            if is_dir:
                shutil.copytree(src, dst, dirs_exist_ok=True)
            else:
                os.makedirs(dst, exist_ok=True)
                for name in sorted(os.listdir(src)):
                    s = os.path.join(src, name)
                    if not os.path.isfile(s):
                        # Skip sub-directories: copy2() on a directory raises
                        # IsADirectoryError.
                        continue
                    copy_file(s, os.path.join(dst, name))
        report.append(f"{kind}: +{added} ~{changed} -{removed}")

    meta = {
        "repo": REPO_URL,
        "commit": commit,
        "version": version if version is not None else "unknown",
    }
    with open(UPSTREAM_MANIFEST, "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
    print("upstream:", meta)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pool-only", action="store_true")
    ap.add_argument("--no-fetch", action="store_true")
    args = ap.parse_args()

    source, ours = resolve_source()
    if not args.no_fetch:
        fetch(source, ours)
    else:
        print("fetch skipped (--no-fetch)")
        if not ours:
            print(f"using omp marketplace cache clone (read-only): {source}")
            check_clean_cache(source)

    commit, version = report_source(source, ours)

    report = []
    refresh_pool(source, report, commit, version)
    for line in report:
        print(line)

    if not args.pool_only:
        print("\nreplaying selection...")
        subprocess.run(
            [sys.executable, os.path.join(ROOT, "tools", "apply_selection.py")], check=True
        )


if __name__ == "__main__":
    main()
