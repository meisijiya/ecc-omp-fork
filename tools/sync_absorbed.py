#!/usr/bin/env python
"""Refresh the absorbed pool: third-party skills this fork ships as its own.

    python tools/sync_absorbed.py              # fetch the pinned commits, rewrite, store
    python tools/sync_absorbed.py --no-fetch   # reuse the local clone cache
    python tools/sync_absorbed.py --dry-run    # report, write nothing

Inputs
  manifest/absorbed.json   per-source pin (repo + commit), the skill list, the
                           bundle recipe, and the sha256 of every stored file
  tools/absorbed_fixups.py declarative rewrites applied to the upstream text

Outputs
  absorbed/<source>/skills/<name>/**   rewritten copies (what gets materialized)
  absorbed/<source>/principles/*.md    raw bundle inputs, kept for regeneration
  manifest/absorbed.json               digests refreshed in place

The stored copy is the *adapted* text, so `tools/apply_selection.py` can copy
it verbatim; `tools/check_absorbed.py` proves offline that the copy was not
hand edited.  A rule that no longer matches upstream fails the run: a silent
half-adaptation is worse than a red gate.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import absorbed_fixups  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ABSORBED = os.path.join(ROOT, "absorbed")
MANIFEST = os.path.join(ROOT, "manifest", "absorbed.json")
CACHE = os.path.join(tempfile.gettempdir(), "ecc-omp-absorbed")

TEXT_SUFFIXES = (".md", ".ts", ".js", ".mjs", ".json", ".sh", ".txt", ".yaml", ".yml")

BUNDLE_INTRO = """\
# Engineering principles

Short, checkable rules for non-trivial engineering work. Each section names
when it applies and what it demands; read the section you need instead of the
whole file.

This file is generated by `tools/sync_absorbed.py` from the absorbed upstream
principle snapshots under `absorbed/pstack/principles/`. Do not edit it by
hand: edit the rewrite rules instead.
"""


def rmtree_force(path):
    """Remove a tree even when a Windows checkout left read-only objects."""
    def onexc(func, target, exc):
        os.chmod(target, stat.S_IWRITE)
        func(target)
    shutil.rmtree(path, onexc=onexc)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def read_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def write_json(path, data):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def git(dest, *args):
    return subprocess.run(("git",) + args, cwd=dest, check=True,
                          capture_output=True, text=True).stdout.strip()


def fetch_source(slug, spec, no_fetch):
    """Return the path of a checkout at the pinned commit.

    The checkout must be byte-identical to the upstream blob, otherwise the
    digests recorded in the manifest describe a Windows-only CRLF copy and a
    clean clone (or CI) would compute different ones.  `core.autocrlf=false`
    on this throwaway repo is what guarantees that.

    A cached clone is only reused when its HEAD is the pinned commit and its
    working tree is clean: `--no-fetch` must not be a way to absorb content
    the manifest does not pin.
    """
    dest = os.path.join(CACHE, slug)
    if no_fetch:
        if not os.path.isdir(os.path.join(dest, ".git")):
            raise SystemExit(
                "--no-fetch but no clone cache at %s; run without --no-fetch once"
                % dest)
        head = git(dest, "rev-parse", "HEAD")
        if head != spec["commit"]:
            raise SystemExit(
                "%s: clone cache is at %s but the manifest pins %s;"
                " rerun without --no-fetch" % (slug, head, spec["commit"]))
        if git(dest, "status", "--porcelain"):
            raise SystemExit(
                "%s: clone cache has local changes; rerun without --no-fetch"
                % slug)
        return dest
    tmp = dest + ".tmp"
    if os.path.isdir(tmp):
        rmtree_force(tmp)
    os.makedirs(tmp)
    git(tmp, "init", "-q")
    git(tmp, "config", "core.autocrlf", "false")
    git(tmp, "remote", "add", "origin", spec["repo"])
    git(tmp, "fetch", "-q", "--depth", "1", "origin", spec["commit"])
    git(tmp, "checkout", "-q", "FETCH_HEAD")
    if os.path.isdir(dest):
        rmtree_force(dest)
    os.replace(tmp, dest)
    return dest


def _excluded(rel, excludes):
    """True when `rel` is one of the excluded paths or sits inside one."""
    for e in excludes:
        e = e.rstrip("/")
        if rel == e or rel.startswith(e + "/"):
            return True
    return False


def store_tree(src, dst, excludes, key_prefix, report):
    """Copy `src` to `dst`, rewriting every .md file on the way."""
    if os.path.isdir(dst):
        rmtree_force(dst)
    for dirpath, dirnames, filenames in os.walk(src):
        rel_dir = os.path.relpath(dirpath, src).replace(os.sep, "/")
        rel_dir = "" if rel_dir == "." else rel_dir + "/"
        dirnames[:] = sorted(
            d for d in dirnames
            if not _excluded(rel_dir + d, excludes))
        for fn in sorted(filenames):
            rel = rel_dir + fn
            if _excluded(rel, excludes):
                continue
            target = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            if fn.endswith(".md"):
                text = open(os.path.join(dirpath, fn), encoding="utf-8").read()
                text, notes = absorbed_fixups.apply_rules(
                    key_prefix + "/" + rel, text)
                if rel == "SKILL.md":
                    text = set_runtime_name(text, key_prefix.split("/")[-1])
                for note in notes:
                    report.append(f"  {key_prefix}/{rel}: {note}")
                with open(target, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
            elif fn.endswith(TEXT_SUFFIXES):
                # the checkout is already LF; normalising again keeps a stray
                # CRLF in the working tree out of the stored copy
                with open(os.path.join(dirpath, fn), "rb") as f:
                    data = f.read().replace(b"\r\n", b"\n")
                with open(target, "wb") as f:
                    f.write(data)
            else:
                shutil.copy2(os.path.join(dirpath, fn), target)


def set_runtime_name(text, upstream_name):
    """The stored copy already carries the name it ships under."""
    runtime = "ecc-omp-" + upstream_name
    return re.sub(r"^name: .*$", "name: " + runtime, text, count=1,
                  flags=re.MULTILINE)


def digest_tree(base):
    out = {}
    for dirpath, _dirnames, filenames in os.walk(base):
        for fn in filenames:
            p = os.path.join(dirpath, fn)
            rel = os.path.relpath(p, base).replace(os.sep, "/")
            out[rel] = sha256_file(p)
    return dict(sorted(out.items()))


def principle_section(text):
    """One bundle section from a stored principle snapshot."""
    body = text.split("\n---\n", 1)[-1].strip("\n")
    lines = body.split("\n")
    title = lines[0].lstrip("# ").strip() if lines and lines[0].startswith("#") else ""
    rest = "\n".join(lines[1:]).strip("\n")
    # sibling-skill links point at files this fork does not ship
    rest = re.sub(
        r"\[[^\]]*\]\(\.\./principle-[^)]*\)", "", rest)
    rest = re.sub(r"\.\./principle-[a-z-]+/SKILL\.md", "", rest)
    rest = re.sub(r"\n{3,}", "\n\n", rest)
    return "## %s\n\n%s\n" % (title, rest)


def bundle_text(spec, source_root=ABSORBED):
    """The bundle skill's full text, regenerated from its stored inputs."""
    stored = os.path.join(source_root, spec["source"], "principles")
    parts = [BUNDLE_INTRO]
    for name in spec["from"]:
        p = os.path.join(stored, name + ".md")
        if not os.path.isfile(p):
            raise SystemExit(f"bundle input missing: {p}")
        parts.append(principle_section(open(p, encoding="utf-8").read()))
    description = (
        "工程原则清单：何时适用 + 具体要求，覆盖幂等、可验证单元、共享状态、"
        "设计空间、第一性原理、体验优先等。非平凡工作开工前或评审时"
        "按需读取对应小节。")
    return (
        "---\n"
        "name: ecc-omp-engineering-principles\n"
        'description: "%s"\n'
        "---\n\n%s" % (description, "\n".join(parts)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-fetch", action="store_true",
                    help="reuse the local clone cache instead of fetching")
    ap.add_argument("--dry-run", action="store_true",
                    help="run the rewrite rules into a scratch tree, write nothing")
    args = ap.parse_args()

    manifest = read_json(MANIFEST)
    bundle = manifest["bundle"]
    report = []
    # a dry run exercises the same code path against a scratch pool, so it
    # catches rule drift instead of only listing what would be touched
    out_root = (tempfile.mkdtemp(prefix="absorbed-dry-") if args.dry_run
                else ABSORBED)

    try:
        for slug, spec in manifest["sources"].items():
            root = fetch_source(slug, spec, args.no_fetch)
            for name, entry in manifest["skills"].items():
                if entry["source"] != slug:
                    continue
                src = os.path.join(root, entry["path"])
                report.append(f"{slug}/{entry['path']} ({name})")
                if not os.path.isdir(src):
                    if name == bundle["skill"]:
                        continue  # generated below, upstream has no such path
                    raise SystemExit(
                        "%s/%s is declared for %r but does not exist upstream"
                        % (slug, entry["path"], name))
                store_tree(
                    src,
                    os.path.join(out_root, slug, entry["path"]),
                    entry.get("exclude", []),
                    slug + "/" + entry["path"],
                    report,
                )
            if slug != bundle["source"]:
                continue
            for name in bundle["from"]:
                rel = "skills/%s/SKILL.md" % name
                report.append(f"{slug}/{rel} (bundle input)")
                source = os.path.join(root, rel)
                if not os.path.isfile(source):
                    raise SystemExit(f"bundle input missing upstream: {source}")
                target = os.path.join(out_root, slug, "principles", name + ".md")
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with open(source, "rb") as f:
                    data = f.read().replace(b"\r\n", b"\n")
                with open(target, "wb") as f:
                    f.write(data)

        bundle_target = os.path.join(
            out_root, bundle["source"], bundle["path"], "SKILL.md")
        os.makedirs(os.path.dirname(bundle_target), exist_ok=True)
        with open(bundle_target, "w", encoding="utf-8", newline="\n") as f:
            f.write(bundle_text(bundle, out_root))
    finally:
        if args.dry_run and os.path.isdir(out_root):
            shutil.rmtree(out_root, ignore_errors=True)

    if args.dry_run:
        print("\n".join(report))
        print("\ndry run: rules replayed against the pinned commits, nothing written")
        return 0

    for name, entry in manifest["skills"].items():
        entry["files"] = digest_tree(
            os.path.join(ABSORBED, entry["source"], entry["path"]))
    bundle["files"] = digest_tree(
        os.path.join(ABSORBED, bundle["source"], "principles"))
    manifest.pop("bundle_skill", None)  # the bundle entry already carries it
    write_json(MANIFEST, manifest)

    print("\n".join(report))
    total = sum(len(e["files"]) for e in manifest["skills"].values())
    print(f"\nabsorbed: {len(manifest['skills'])} skills, {total} files, "
          f"manifest digests refreshed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
